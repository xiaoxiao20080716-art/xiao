#include "stm32f10x.h"                  // 芯片的“说明书”头文件（Device header）
#include "Delay.h"                      // 延时函数
#include "OLED.h"                       // OLED 显示屏（本例子没往屏幕上显示东西，先留着备用）
#include "PWM.h"                        // 我们自己写的 PWM 驱动

uint8_t i;                              // 循环计数用的小变量（能装0~255，这里最大用到100）

/*==========================================================================
 * 主函数：单片机上电后就从这里开始跑，而且永远不结束
 *========================================================================*/
int main(void)
{
	OLED_Init();       // 初始化 OLED 屏幕
	PWM_Init();        // 初始化 PWM：PA0 引脚开始输出 100Hz 的方波

	while (1)          // 死循环：单片机程序必须一直在这里面转，不能退出
	{
		/* 第一个循环：占空比从 0% 慢慢加到 100%
		 * 效果：接在 PA0 上的 LED 越来越亮（接电机的话就是越来越快）
		 * 一共 101 次，每次停 10ms，所以大约 1 秒钟走完一趟
		 */
		for (i = 0; i <= 100; i++)
		{
			PWM_SetCompare1(i);        // 把占空比设成 i%
			Delay_ms(5);              // 停 10 毫秒，让肉眼看得出变化（不停的话瞬间就跳完了）
		}

		/* 第二个循环：占空比从 100% 慢慢降回 0%
		 * 效果：LED 越来越暗（接电机的话就是越来越慢）
		 * 100 - i 的意思是：i 从 0 加到 100 的时候，100-i 正好从 100 减到 0
		 */
		for (i = 0; i <= 100; i++)
		{
			PWM_SetCompare1(100 - i);  // 把占空比设成 (100-i)%
			Delay_ms(5);
		}
	}
}
